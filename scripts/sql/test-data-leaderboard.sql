-- 已保存分组：胜率只统计已结束队内赛 + 已保存分组 + 比分已知的场次。
-- 分组按出席名单生成，A 队（team=0）与事件 team=0 一致；
-- 比分判定：1007/1008/1009/1011/1012/1013/1015 A 胜，1014 B 胜，1010/1016 平局。
-- ---------------------------------------------------------------------------
INSERT INTO match_grouping (id, match_id, manual_weight, auto_weight, roster_fingerprint,
                            generated_at, saved_at, created_by)
SELECT 4000 + m.season_match_no, m.id, 100.00, 0.00,
       SHA2(CONCAT('grouping-', m.id), 256),
       DATE_SUB(m.start_at, INTERVAL 2 DAY), DATE_SUB(m.start_at, INTERVAL 1 DAY), 1001
FROM team_match m
WHERE m.id BETWEEN 1007 AND 1016;

INSERT INTO match_grouping_player (grouping_id, player_id, team, manual_score, final_score)
SELECT g.id, a.player_id,
       CASE WHEN a.player_id IN (1001, 1002, 1003, 1006, 1007, 1011, 1012, 1015,
                                 1030, 1031, 1040, 1042, 1048, 1055) THEN 0 ELSE 1 END,
       p.skill, p.skill
FROM match_grouping g
JOIN attendance a ON a.match_id = g.match_id AND a.status = 0 AND a.is_deleted = 0
JOIN player p ON p.id = a.player_id
WHERE g.match_id BETWEEN 1007 AND 1016
  AND a.player_id IN (1001, 1002, 1003, 1006, 1007, 1011, 1012, 1015, 1030, 1031, 1040, 1042, 1048, 1055,
